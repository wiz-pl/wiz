#!/usr/bin/env node
// Build the prototype artefacts from one kernel file:
//
//   WIZ=/path/to/wiz node webgpu/tools/make.mjs
//
//   1. webgpu/build/<kernel>.wgsl          the generated WGSL (via tools/wgsl.mjs)
//   2. webgpu/build/ref.wiz                the same source + #eval of the scalar kernel
//   3. webgpu/build/expected.json          the numbers `wiz check` printed (the interpreter)
//
// The WGSL and expected.json are committed, so the page and the Deno check work from a
// checkout without a Wiz binary; this script is how they are regenerated.

import { execFileSync, spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');            // webgpu/
const repo = resolve(root, '..');            // repository root
const kernelFile = join(root, 'kernels', 'add.wiz');
const inputs = JSON.parse(readFileSync(join(root, 'inputs.json'), 'utf8'));
const build = join(root, 'build');
const wiz = process.env.WIZ || 'wiz';
const KERNELS = ['add', 'maxMul'];

mkdirSync(build, { recursive: true });

// 1. WGSL, one module per entry point.
for (const entry of KERNELS) {
  execFileSync(process.execPath, [join(here, 'wgsl.mjs'),
    '--input', kernelFile, '--entry', entry, '--out', join(build, `${entry}.wgsl`), '--wiz', wiz,
  ], { stdio: ['ignore', 'inherit', 'inherit'] });
}

// 2. The reference program.  It contains the *same* kernel source, so the interpreter is
// running the definition the WGSL was emitted from, not a hand-copied paraphrase.  The
// interpreter cannot execute `Array` (the externs are compiled code only: `#eval` panics
// with "foreign functions only run in compiled code"), so the reference applies the
// scalar kernel to the inputs; buffer indexing is the only part not interpreted.
const SCALAR = { add: 'addScalar', maxMul: 'maxMulScalar' };
const evals = KERNELS.flatMap((entry) =>
  inputs.a.map((x, i) =>
    `#eval UIntN.toNat (${SCALAR[entry]} (U32.ofNat ${x}) (U32.ofNat ${inputs.b[i]}))`));
const ref = `${readFileSync(kernelFile, 'utf8')}\n` +
  `-- generated by webgpu/tools/make.mjs: the interpreter's reference for inputs.json\n` +
  `${evals.join('\n')}\n`;
writeFileSync(join(build, 'ref.wiz'), ref);

// 3. Run the interpreter.  `wiz check` prints one `info: N` line per #eval; the lines may
// be on stdout or stderr, so both are parsed and both are shown when it fails.
const run = spawnSync(wiz, ['check', join(build, 'ref.wiz')], { cwd: repo, encoding: 'utf8' });
const output = (run.stdout || '') + (run.stderr || '');
if (run.status !== 0) {
  process.stderr.write(output);
  console.error(`make: \`${wiz} check webgpu/build/ref.wiz\` failed (exit ${run.status})`);
  process.exit(1);
}
const values = [...output.matchAll(/\binfo:\s*(\d+)\s*$/gm)].map((m) => Number(m[1]));
if (values.length !== KERNELS.length * inputs.a.length) {
  console.error(`make: expected ${KERNELS.length * inputs.a.length} #eval results, got ${values.length}:\n${output}`);
  process.exit(1);
}

const kernels = {};
KERNELS.forEach((entry, k) => {
  kernels[entry] = {
    entry,
    wgsl: `${entry}.wgsl`,
    values: values.slice(k * inputs.a.length, (k + 1) * inputs.a.length),
  };
});
const expected = {
  note: 'values are the Wiz interpreter\'s, from `wiz check webgpu/build/ref.wiz` (#eval); do not edit by hand',
  kernelSource: 'webgpu/kernels/add.wiz',
  length: inputs.a.length,
  a: inputs.a,
  b: inputs.b,
  kernels,
};
writeFileSync(join(build, 'expected.json'), JSON.stringify(expected, null, 2) + '\n');
for (const [name, k] of Object.entries(kernels)) console.error(`make: ${name} = [${k.values.join(', ')}]`);
console.error('make: wrote build/add.wgsl, build/maxMul.wgsl, build/ref.wiz, build/expected.json');
