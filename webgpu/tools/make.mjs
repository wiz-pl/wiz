#!/usr/bin/env node
// Build the prototype artefacts from one kernel file:
//
//   WIZ=/path/to/wiz node webgpu/tools/make.mjs
//
//   1. webgpu/build/<kernel>.wgsl          the generated WGSL (via tools/wgsl.mjs)
//   2. webgpu/build/ref.wiz                the same source + #eval of the entry kernels
//   3. webgpu/build/expected.json          the numbers `wiz check` printed (the interpreter)
//   4. webgpu/build/wide.json              the same for 130 elements (three workgroups, so
//                                          the dispatch guard and a partial last group run)
//
// The WGSL and expected files are committed, so the page and the Deno check work from a
// checkout without a Wiz binary; this script is how they are regenerated.

import { execFileSync, spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');            // webgpu/
const repo = resolve(root, '..');            // repository root
const kernelRel = 'webgpu/kernels/add.wiz';  // relative, so the generated header is portable
const kernelFile = join(repo, kernelRel);
const inputs = JSON.parse(readFileSync(join(root, 'inputs.json'), 'utf8'));
const build = join(root, 'build');
const wiz = process.env.WIZ || 'wiz';
const KERNELS = ['add', 'maxMul', 'mix'];

mkdirSync(build, { recursive: true });

// 1. WGSL, one module per entry point.
for (const entry of KERNELS) {
  execFileSync(process.execPath, [join(here, 'wgsl.mjs'),
    '--input', kernelRel, '--entry', entry, '--out', join(build, `${entry}.wgsl`), '--wiz', wiz,
  ], { cwd: repo, stdio: ['ignore', 'inherit', 'inherit'] });
}

// A wide input crosses the 64-invocation workgroup boundary (130 = 2 full groups + 2),
// so the generated `if (i < arrayLength(&out))` guard and the dispatch count are tested.
const WIDE = 130;
const wide = {
  a: Array.from({ length: WIDE }, (_, i) => (i * 2654435761) >>> 0),
  b: Array.from({ length: WIDE }, (_, i) => (i * 40503 + 7) >>> 0),
};

// 2. The reference program.  It contains the *same* kernel source, so the interpreter is
// running the definition the WGSL was emitted from, not a hand-copied paraphrase.  On
// this base `#eval` has an Array model, so the reference calls the entry kernel itself:
// Array.getD, the buffer indexing and the index parameter are interpreted too, not just
// the scalar helper.
const SETS = [
  ['narrow', 'aNarrow', 'bNarrow', inputs.a, inputs.b],
  ['wide', 'aWide', 'bWide', wide.a, wide.b],
];
const wizList = (xs) => `[${xs.map((n) => `U32.ofNat ${n}`).join(', ')}]`;
const arrayDefs = SETS.flatMap(([, aName, bName, as, bs]) => [
  `def ${aName} : Array U32 := ofList ${wizList(as)}`,
  `def ${bName} : Array U32 := ofList ${wizList(bs)}`,
]).join('\n');
const evals = SETS.flatMap(([, aName, bName, as]) => KERNELS.flatMap((entry) =>
  as.map((_, i) => `#eval UIntN.toNat (${entry} ${i} ${aName} ${bName})`)));
const ref = `${readFileSync(kernelFile, 'utf8')}\n` +
  `-- generated by webgpu/tools/make.mjs: the interpreter's reference for inputs.json\n` +
  `def ofListGo : List U32 → Array U32 → Array U32\n` +
  `  | .nil, acc => acc\n` +
  `  | .cons x xs, acc => ofListGo xs (Array.push acc x)\n` +
  `def ofList (l : List U32) : Array U32 := ofListGo l Array.empty\n` +
  `${arrayDefs}\n` +
  `${evals.join('\n')}\n`;
writeFileSync(join(build, 'ref.wiz'), ref);

// 3. Run the interpreter.  `wiz check` prints one `info: N` line per #eval; the lines may
// be on stdout or stderr, so both are parsed and both are shown when it fails.
const run = spawnSync(wiz, ['check', join(build, 'ref.wiz')], { cwd: repo, encoding: 'utf8' });
const output = (run.stdout || '') + (run.stderr || '');
if (run.status !== 0) {
  process.stderr.write(output);
  console.error(`make: \`${wiz} check webgpu/build/ref.wiz\` failed (exit ${run.status})`);
  process.exit(1);
}
const values = [...output.matchAll(/\binfo:\s*(\d+)\s*$/gm)].map((m) => Number(m[1]));
if (values.length !== KERNELS.length * (inputs.a.length + WIDE)) {
  console.error(`make: expected ${KERNELS.length * (inputs.a.length + WIDE)} #eval results, got ${values.length}:\n${output}`);
  process.exit(1);
}

const narrowKernels = {};
KERNELS.forEach((entry, k) => {
  narrowKernels[entry] = {
    entry,
    wgsl: `${entry}.wgsl`,
    values: values.slice(k * inputs.a.length, (k + 1) * inputs.a.length),
  };
});
const expected = {
  note: 'values are the Wiz interpreter\'s, from `wiz check webgpu/build/ref.wiz` (#eval); do not edit by hand',
  kernelSource: 'webgpu/kernels/add.wiz',
  length: inputs.a.length,
  a: inputs.a,
  b: inputs.b,
  kernels: narrowKernels,
};
writeFileSync(join(build, 'expected.json'), JSON.stringify(expected, null, 2) + '\n');

const wideKernels = {};
KERNELS.forEach((entry, k) => {
  const start = KERNELS.length * inputs.a.length + k * WIDE;
  wideKernels[entry] = {
    entry,
    wgsl: `${entry}.wgsl`,
    values: values.slice(start, start + WIDE),
  };
});
const wideExpected = {
  note: 'values are the Wiz interpreter\'s, from `wiz check webgpu/build/ref.wiz` (#eval); do not edit by hand',
  kernelSource: 'webgpu/kernels/add.wiz',
  length: WIDE,
  a: wide.a,
  b: wide.b,
  kernels: wideKernels,
};
writeFileSync(join(build, 'wide.json'), JSON.stringify(wideExpected, null, 2) + '\n');

for (const [name, k] of Object.entries(narrowKernels)) console.error(`make: ${name} = [${k.values.join(', ')}]`);
console.error(`make: wrote build/{${KERNELS.join(',')}}.wgsl, build/ref.wiz, ` +
  `build/expected.json (${KERNELS.length * inputs.a.length} values), ` +
  `build/wide.json (${KERNELS.length * WIDE} values)`);
