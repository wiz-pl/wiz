#!/bin/sh
# LLVM source-based coverage for one Wiz program through the C backend.
#
#   scripts/coverage/wiz-c-coverage.sh FILE OUTDIR [-- PROGRAM-ARGS...]
#
# `wiz build -o OUT` already writes the generated C beside the executable, as
# OUT.c (`Wiz/Compiler/Build.lean:155`, `compileC` writes `exe.withExtension "c"`
# before it calls the compiler), so there is no `--emit-c` to add and no shim to
# capture a temporary: this driver builds with `-fprofile-instr-generate
# -fcoverage-mapping`, runs the program, merges the profile, and reports on OUT.c.
#
# The C file carries no `#line` directives back to the `.wiz` source
# (`Wiz/Compiler/C.lean` emits none; only the BPF backend does), so every number
# below is generated-C coverage, not Wiz-source coverage. The analyzer prints that
# limitation in the summary too.
#
# Environment:
#   WIZ                 the compiler (default: wiz on PATH)
#   WIZ_COV_CLANG       clang to use (default: clang on PATH); it must be the same
#                       major version as llvm-cov/llvm-profdata
#   WIZ_COV_LLVM_COV    llvm-cov (default: llvm-cov on PATH)
#   WIZ_COV_PROFDATA    llvm-profdata (default: llvm-profdata on PATH)
#   WIZ_COV_CFLAGS      extra C flags, e.g. the GMP include
#   WIZ_COV_LDFLAGS     extra link flags, e.g. the GMP library directory
#
# `wiz build` needs GMP. The recorded invocation on this checkout is:
#
#   WIZ_COV_CLANG=/nix/store/.../bin/clang \
#   WIZ_COV_LLVM_COV=/nix/store/.../bin/llvm-cov \
#   WIZ_COV_PROFDATA=/nix/store/.../bin/llvm-profdata \
#   WIZ_COV_CFLAGS=-I/nix/store/...-gmp.../include \
#   WIZ_COV_LDFLAGS=-L/nix/store/...-gmp.../lib \
#     scripts/coverage/wiz-c-coverage.sh examples/array.wiz OUT
#
# or, when a clang and LLVM 21 are on PATH (e.g. `nix shell nixpkgs#clang_21
# nixpkgs#llvm_21 nixpkgs#gmp.dev`), just
#
#   scripts/coverage/wiz-c-coverage.sh examples/array.wiz OUT
#
# Exit status: 0 the reports were produced (the program's own exit status is recorded
# in OUTDIR/exit-code and the summary); 1 build/run/report failure; 2 usage.
set -eu

usage() {
  echo "usage: $0 FILE OUTDIR [-- PROGRAM-ARGS...]" >&2
  exit 2
}

[ $# -ge 2 ] || usage
file=$1
out=$2
shift 2
if [ "${1:-}" = "--" ]; then shift; fi

[ -f "$file" ] || { echo "$0: no such file: $file" >&2; exit 2; }

wiz=${WIZ:-wiz}
clang=${WIZ_COV_CLANG:-clang}
cov=${WIZ_COV_LLVM_COV:-llvm-cov}
profdata=${WIZ_COV_PROFDATA:-llvm-profdata}

for tool in "$wiz" "$clang" "$cov" "$profdata"; do
  if ! command -v "$tool" >/dev/null 2>&1 && [ ! -x "$tool" ]; then
    echo "$0: not found: $tool (set WIZ, WIZ_COV_CLANG, WIZ_COV_LLVM_COV," \
         "WIZ_COV_PROFDATA, or use nix shell nixpkgs#clang_21 nixpkgs#llvm_21)" >&2
    exit 1
  fi
done

mkdir -p "$out"
# A previous run's profile would be merged with this one; remove the files this
# driver writes, and nothing else.
rm -f "$out/prog" "$out/prog.c" "$out/prog.profraw" "$out/prog.profdata" \
      "$out/report.txt" "$out/functions.txt" "$out/show.txt" "$out/export.json" \
      "$out/summary.txt" "$out/stdout" "$out/stderr" "$out/exit-code" \
      "$out/commands.txt" "$out/build.txt"

cflags="-O0 -g -fprofile-instr-generate -fcoverage-mapping ${WIZ_COV_CFLAGS:-}"
ldflags="-fprofile-instr-generate ${WIZ_COV_LDFLAGS:-}"

cat > "$out/commands.txt" <<EOF
# generated by scripts/coverage/wiz-c-coverage.sh
WIZ=$wiz
CLANG=$clang
LLVM_COV=$cov
LLVM_PROFDATA=$profdata
CFLAGS=$cflags
LDFLAGS=$ldflags
$wiz build $file -o $out/prog --cc $clang --cflags "$cflags" --ldflags "$ldflags"
LLVM_PROFILE_FILE=$out/prog.profraw $out/prog $*
$profdata merge -sparse $out/prog.profraw -o $out/prog.profdata
(cd $out && $cov report $out/prog -instr-profile=$out/prog.profdata)
(cd $out && $cov report $out/prog -instr-profile=$out/prog.profdata -compilation-dir=$out -sources prog.c --show-functions)
(cd $out && $cov show $out/prog -instr-profile=$out/prog.profdata -compilation-dir=$out prog.c)
$cov export $out/prog -instr-profile=$out/prog.profdata -format=text
EOF

echo "== build: $file"
if ! "$wiz" build "$file" -o "$out/prog" --cc "$clang" \
       --cflags "$cflags" --ldflags "$ldflags" >"$out/build.txt" 2>&1; then
  cat "$out/build.txt" >&2
  echo "$0: build failed (see $out/build.txt)" >&2
  exit 1
fi
[ -f "$out/prog.c" ] || { echo "$0: no generated C at $out/prog.c" >&2; exit 1; }

echo "== run"
set +e
LLVM_PROFILE_FILE="$out/prog.profraw" "$out/prog" "$@" >"$out/stdout" 2>"$out/stderr"
run=$?
set -e
printf '%s\n' "$run" > "$out/exit-code"
[ -f "$out/prog.profraw" ] || {
  echo "$0: no profile written (the program exited $run before a clean exit)" >&2
  exit 1
}

"$profdata" merge -sparse "$out/prog.profraw" -o "$out/prog.profdata"
(cd "$out" && "$cov" report "$out/prog" -instr-profile="$out/prog.profdata") > "$out/report.txt"

# The compiler may record the generated C as an absolute path or as one relative to
# the build directory (`-ffile-prefix-map`); ask the report which it is, then give
# llvm-cov both the directory it is relative to and that directory as the cwd.
cname=$(sed -n '/prog\.c/ { s/^[[:space:]]*//; s/[[:space:]].*//; p; q; }' "$out/report.txt")
[ -n "$cname" ] || { echo "$0: cannot find prog.c in $out/report.txt" >&2; exit 1; }
case "$cname" in
  /*) cdir=/ ;;
  *)  cdir=$out ;;
esac

(cd "$cdir" && "$cov" report "$out/prog" -instr-profile="$out/prog.profdata" \
   -compilation-dir="$cdir" -sources "$cname" --show-functions) > "$out/functions.txt"
(cd "$cdir" && "$cov" show "$out/prog" -instr-profile="$out/prog.profdata" \
   -compilation-dir="$cdir" "$cname") > "$out/show.txt"
"$cov" export "$out/prog" -instr-profile="$out/prog.profdata" -format=text > "$out/export.json"

python3 "$(dirname "$0")/wiz-c-coverage.py" \
  --c "$out/prog.c" --export "$out/export.json" --show "$out/show.txt" \
  --report "$out/report.txt" --exit-code "$run" | tee "$out/summary.txt"

echo "== reports: $out/{report,functions,show}.txt $out/export.json"
