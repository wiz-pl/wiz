#!/usr/bin/env python3
"""Generate `Tests/data/kernel-ctx-probe.wiz`, the `#eval`-heavy probe for the kernel
context change (arrays indexed by level + sparse usage vectors).

The probe is deliberately deep: a term that uses the **outermost** of N binders forces a
de Bruijn lookup and a usage vector of length N (the worst case for both
representations), while a term that uses the **innermost** binder leaves a sparse usage
vector of length 1 (the case the sparse representation exists for). N is large enough
for the difference between `List` indexing and `Array` indexing to be visible without
making a single run minutes long.

The generated file is committed so a measurement never depends on this script. Rerun it
only to change N or the number of `#eval`s:

    python3 scripts/gen-kernel-ctx-probe.py

The queue lane's before/after recipe is in `docs/notes/kernel-ctx-arrays.md`.
"""
from pathlib import Path

N = 192
EVALS = 48

def arrows(n: int) -> str:
    return " → ".join(["Nat"] * n)

def binders(n: int, start: int = 0) -> str:
    return " ".join(f"(ω x{start + i})" for i in range(n))

def args(n: int) -> str:
    return " ".join(str(i % 10) for i in range(n))

lines = [
    "import Prelude",
    "",
    f"-- Generated by scripts/gen-kernel-ctx-probe.py: {N} binders, {EVALS} #eval lines.",
    "-- The outermost variable is used: a de Bruijn lookup at index N-1 and a usage",
    "-- vector with N-1 interior zeros (the worst case for the list representation).",
    f"def deepFirst : {arrows(N)} → Nat := fun {binders(N)} => x0",
    "",
    "-- The innermost variable is used: a lookup at index 0 and a sparse usage vector of",
    "-- length 1 (the case the sparse representation is for).",
    f"def deepLast : {arrows(N)} → Nat := fun {binders(N)} => x{N - 1}",
    "",
    "-- The outermost variable is linear and used once; the rest are ω and unused.",
    f"def deepLinear : (1 x0 : Nat) → {arrows(N - 1)} → Nat := fun (1 x0) {binders(N - 1, start=1)} => x0",
    "",
    "#eval deepFirst " + args(N),
    "#eval deepLast " + args(N),
    "#eval deepLinear " + args(N),
    "",
]
for k in range(EVALS):
    which = ["deepFirst", "deepLast", "deepLinear"][k % 3]
    lines.append(f"#eval {which} " + args(N))
lines.append("")

out = Path(__file__).resolve().parent.parent / "Tests" / "data" / "kernel-ctx-probe.wiz"
out.write_text("\n".join(lines), encoding="utf-8")
print(f"wrote {out} ({len(lines)} lines)")
