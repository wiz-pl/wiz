// The widget front end scenario, shared by the headless-browser test and the Node
// fallback.  Both drive `WidgetView` (tools/jupyter/static/widget.js) with a fake comm
// and assert the same DOM, so the Node run checks the pure patcher and the browser run
// checks what the real DOM does with it (form-control value properties, real events,
// attribute serialisation).
//
// This is the *widget* encoding: roots carry `data-wiz-widget`, the control carries
// `data-wiz-widget-input`, and events travel as
// `{method: "event", widget_id, event, value}`.  The fixture is generated from
// `Web.Widget` by `widget_gen.sh`, so the bundles and patch lists are the kernel's.
//
// `runScenario` takes a tiny DOM adapter:
//   { parse, click(el), input(el, value), liveValue }
// `parse` is undefined for a browser (runtime.js's `document` parser) and
// `minidom.parse` under Node.  `liveValue` says the adapter exposes form-control value
// properties, which minidom deliberately does not.
"use strict";

import { WidgetView } from "./widget.js";
import { FakeComm, FakeKernel } from "./fake_comm.mjs";

const WIDGET_IDS = ["readout", "inc", "level"];
const VOID = new Set(["area", "base", "br", "col", "embed", "hr", "img", "input",
  "link", "meta", "param", "source", "track", "wbr"]);

// The fixture is generated by `widget_gen.wiz`; these are the things a rendering
// regression must not change (the serialised HTML is pinned by the goldens instead).
const INITIAL = {
  elements: 8,
  tags: { div: 1, span: 2, input: 2, output: 2, button: 1 },
  ids: WIDGET_IDS,
  text: { readout: "count 0", inc: "+", level: "1" },
  attrs: {
    readout: { "data-wiz-widget-kind": "text", "data-wiz-widget-event": "input",
      "data-wiz-widget-value": "count 0" },
    inc: { "data-wiz-widget-kind": "button", "data-wiz-widget-event": "click",
      "data-wiz-widget-value": "count 1", type: "button" },
    level: { "data-wiz-widget-kind": "slider", "data-wiz-widget-event": "input",
      "data-wiz-widget-value": "1" },
  },
  controls: {
    readout: { type: "text", value: "count 0" },
    level: { type: "range", min: "0", max: "3", step: "1", value: "1" },
  },
};

export function runScenario({ root, fixture, dom }) {
  const checks = [];
  const ok = (cond, what, detail = "") => {
    if (!cond) throw new Error("FAIL: " + what + (detail ? "\n  " + detail : ""));
    checks.push(what);
  };
  const same = (a, b) => JSON.stringify(a) === JSON.stringify(b);

  const elements = () => {
    const out = [];
    for (const child of children(root)) findAll(child, isElement, out);
    return out;
  };
  const widgets = () => findAll(root, (n) => isElement(n) && n !== root
    && n.getAttribute("data-wiz-widget") != null);
  const byWidget = (id) => find(root, (n) => isElement(n)
    && n.getAttribute("data-wiz-widget") === id);
  const control = (id) => find(root, (n) => isElement(n)
    && n.getAttribute("data-wiz-widget-input") === id);
  const text = (id) => {
    const n = byWidget(id);
    if (!n) throw new Error("no [data-wiz-widget=" + id + "]");
    return n.textContent;
  };
  const attr = (node, name) => {
    if (!node) throw new Error("no node for " + name);
    return node.getAttribute(name);
  };
  const serialised = () => serializeChildren(root);

  ok(elements().length === 0, "the container is empty before comm_open");

  const comm = new FakeComm({ comm_id: fixture.comm_id, target_name: fixture.target_name });
  const kernel = new FakeKernel(fixture, comm);
  const view = new WidgetView(root, { parse: dom.parse });
  view.bindComm(comm);
  kernel.start();

  // -- first render ----------------------------------------------------
  ok(elements().length === INITIAL.elements,
    "the first render has " + INITIAL.elements + " elements", String(elements().length));
  const tagCounts = {};
  for (const n of elements()) tagCounts[tag(n)] = (tagCounts[tag(n)] || 0) + 1;
  ok(same(tagCounts, INITIAL.tags), "the first render's element counts", JSON.stringify(tagCounts));

  ok(same(widgets().map((n) => n.getAttribute("data-wiz-widget")), INITIAL.ids),
    "the data-wiz-widget ids, in document order",
    JSON.stringify(widgets().map((n) => n.getAttribute("data-wiz-widget"))));
  for (const [id, want] of Object.entries(INITIAL.text)) {
    ok(text(id) === want, "[data-wiz-widget=" + id + "] says " + JSON.stringify(want),
      JSON.stringify(text(id)));
  }
  for (const [id, attrs] of Object.entries(INITIAL.attrs)) {
    for (const [name, want] of Object.entries(attrs)) {
      ok(attr(byWidget(id), name) === want,
        "[data-wiz-widget=" + id + "] has " + name + "=" + JSON.stringify(want),
        JSON.stringify(attr(byWidget(id), name)));
    }
  }
  for (const [id, attrs] of Object.entries(INITIAL.controls)) {
    for (const [name, want] of Object.entries(attrs)) {
      ok(attr(control(id), name) === want,
        "the " + id + " control has " + name + "=" + JSON.stringify(want),
        JSON.stringify(attr(control(id), name)));
    }
  }
  ok(serialised() === fixture.display.html,
    "the first render's serialised DOM is the SSR fixture",
    "\n  got  " + serialised() + "\n  want " + fixture.display.html);
  ok(comm.received.length === 1 && comm.received[0].header.msg_type === "comm_open",
    "the kernel opened the comm");
  ok(comm.received[0].content.target_name === fixture.target_name,
    "comm_open has the widget target", JSON.stringify(comm.received[0].content.target_name));
  ok(comm.received[0].content.data.schema === "wiz.widget/1",
    "comm_open carries a wiz.widget/1 bundle");
  ok(comm.received[0].content.data.html === fixture.display.html,
    "comm_open carries the initial SSR HTML");
  ok(comm.received[0].header.version === "5.3", "comm_open uses protocol 5.3");

  const initial = serialised();

  // -- a button click --------------------------------------------------
  dom.click(byWidget("inc"));
  ok(comm.sent.length === 1, "a click sends one message to the kernel", JSON.stringify(comm.sent));
  ok(same(comm.sent[0], fixture.steps.click.payload),
    "a click sends {method, widget_id, event, value}", JSON.stringify(comm.sent[0]));
  ok(comm.received.length === 2, "the kernel answered the click");
  const afterClickMsg = comm.received[1];
  ok(afterClickMsg.header.msg_type === "comm_msg" && afterClickMsg.content.data.method === "update",
    "the click is answered with a comm_msg update", JSON.stringify(afterClickMsg.content));
  ok(same(afterClickMsg.content.data.patches, fixture.steps.click.patches),
    "the click carries the Wiz patch list", JSON.stringify(afterClickMsg.content.data.patches));
  ok(text("readout") === "count 1", "the readout says count 1", JSON.stringify(text("readout")));
  ok(elements().length === INITIAL.elements, "the click patch keeps the element count");
  ok(same(widgets().map((n) => n.getAttribute("data-wiz-widget")), WIDGET_IDS),
    "the click patch keeps every data-wiz-widget id");
  ok(serialised() === fixture.steps.click.html, "the click's serialised DOM matches the next SSR",
    "\n  got  " + serialised() + "\n  want " + fixture.steps.click.html);
  const afterClick = serialised();

  // -- the slider ------------------------------------------------------
  const slider = control("level");
  dom.input(slider, "3");
  ok(comm.sent.length === 2, "a slider input sends one message to the kernel", JSON.stringify(comm.sent));
  ok(same(comm.sent[1], fixture.steps.input.payload),
    "a slider input sends its value", JSON.stringify(comm.sent[1]));
  ok(kernel.steps.join(",") === "click,input", "the kernel saw click then input",
    JSON.stringify(kernel.steps));
  const afterInputMsg = comm.received[2];
  ok(afterInputMsg.header.msg_type === "comm_msg" && afterInputMsg.content.data.method === "update",
    "the slider is answered with a comm_msg update");
  ok(same(afterInputMsg.content.data.patches, fixture.steps.input.patches),
    "the slider carries the Wiz patch list", JSON.stringify(afterInputMsg.content.data.patches));
  ok(attr(control("level"), "value") === "3", "the slider's value attribute is 3",
    JSON.stringify(attr(control("level"), "value")));
  ok(text("level") === "3", "the level text is 3", JSON.stringify(text("level")));
  ok(text("readout") === "3", "the readout follows the slider", JSON.stringify(text("readout")));
  ok(attr(byWidget("level"), "data-wiz-widget-event") === "input",
    "the slider keeps its event attribute");
  ok(attr(control("level"), "type") === "range" && attr(control("level"), "min") === "0"
    && attr(control("level"), "max") === "3" && attr(control("level"), "step") === "1",
    "the slider keeps its untouched attributes");
  ok(elements().length === INITIAL.elements, "the slider patch keeps the element count");
  ok(same(widgets().map((n) => n.getAttribute("data-wiz-widget")), WIDGET_IDS),
    "the slider patch keeps every data-wiz-widget id");
  ok(serialised() === fixture.steps.input.html, "the slider's serialised DOM matches the next SSR",
    "\n  got  " + serialised() + "\n  want " + fixture.steps.input.html);
  const afterInput = serialised();

  // The live property is the bug the Node test double cannot see: `setAttribute` sets
  // the *default* value, and a control the user has edited keeps its own value.  The
  // patcher mirrors `value` into the property; only a real DOM has one.
  if (dom.liveValue) {
    ok(slider.value === "3", "the live range value follows the patch", JSON.stringify(slider.value));
  }

  ok(comm.received.every((m) => m.header.msg_type !== "comm_msg"
      || m.content.data.method !== "error"),
    "the kernel rejected no event", JSON.stringify(comm.received.map((m) => m.content.data)));
  ok(comm.messages.join(",") === "comm_open,comm_msg,comm_msg",
    "the comm saw open and two updates", JSON.stringify(comm.messages));

  return {
    checks,
    initial,
    afterClick,
    afterInput,
    sent: comm.sent,
    received: comm.received.map((m) => ({
      msg_type: m.header.msg_type, version: m.header.version, content: m.content,
    })),
    kernelSteps: kernel.steps,
  };
}

// -- a browser DOM adapter ----------------------------------------------

export const browserDom = {
  parse: undefined, // runtime.js's document.createRange() parser
  liveValue: true,
  click: (el) => {
    el.dispatchEvent(new MouseEvent("click", { bubbles: true, cancelable: true }));
  },
  input: (el, value) => {
    el.value = value;
    el.dispatchEvent(new Event("input", { bubbles: true }));
  },
};

export function runBrowserScenario(root, fixture) {
  return runScenario({ root, fixture, dom: browserDom });
}

// -- a Node DOM adapter (minidom) ---------------------------------------

export function runNodeScenario(fixture, { parse }) {
  const root = parse("");
  const dom = {
    parse,
    liveValue: false,
    click: (el) => el.dispatchEvent({ type: "click" }),
    input: (el, value) => {
      el.value = value; // read by widget.js; minidom has no value property of its own
      el.dispatchEvent({ type: "input" });
    },
  };
  return runScenario({ root, fixture, dom });
}

// -- DOM helpers that work on both a browser tree and minidom ------------

function isElement(n) {
  return n.nodeType === 1 || typeof n.tagName === "string";
}

function tag(n) {
  return String(n.tagName || n.nodeName || "").toLowerCase();
}

function find(n, pred) {
  if (pred(n)) return n;
  for (const c of children(n)) {
    const hit = find(c, pred);
    if (hit) return hit;
  }
  return null;
}

function findAll(n, pred, out = []) {
  if (pred(n)) out.push(n);
  for (const c of children(n)) findAll(c, pred, out);
  return out;
}

function children(n) {
  return Array.from(n.childNodes || []);
}

function attrPairs(n) {
  if (typeof n.getAttributeNames === "function") {
    return n.getAttributeNames().map((name) => [name, n.getAttribute(name)]);
  }
  return Array.from(n.attrs ? n.attrs.entries() : []);
}

function serializeChildren(root) {
  return children(root).map(serializeNode).join("");
}

function serializeNode(n) {
  if (!isElement(n)) return esc(n.data !== undefined ? n.data : n.textContent);
  const name = tag(n);
  const attrs = attrPairs(n).map(([k, v]) => " " + k + "=\"" + esc(v) + "\"").join("");
  const open = "<" + name + attrs + ">";
  if (VOID.has(name)) return open;
  return open + children(n).map(serializeNode).join("") + "</" + name + ">";
}

// The same escaping as `Tagged.esc` in lib/Tagged.wiz and minidom.mjs.
function esc(s) {
  return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;").replace(/'/g, "&#39;");
}
