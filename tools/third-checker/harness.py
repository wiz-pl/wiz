#!/usr/bin/env python3
"""Run the third checker over the committed corpus, or regenerate the dump.

    python3 tools/third-checker/harness.py            # check the committed dump
    python3 tools/third-checker/harness.py --regen    # re-run the selfhost kernel

The dump is produced by `tools/third-checker/driver.py`: the self-hosted kernel
(`selfhost/Kernel.wiz`) checks every declaration and prints the term it accepted (or the
term it rejected).  The checker in `checker.py` re-checks each serialized term from
scratch.  A disagreement is a mismatch; it is the only interesting output.

`--regen` needs a working `wiz` binary and a C compiler (`wiz run` compiles the driver).
In this checkout that is `nix develop` (see README.md).  The committed dump means normal
runs need neither.
"""

import argparse
import os
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, HERE)

import checker  # noqa: E402

DUMP = os.path.join(HERE, "corpus.dump")
DRIVER = os.path.join(HERE, "driver.py")


def regen(wiz_bin, timeout):
    src = subprocess.check_output([sys.executable, DRIVER, "--emit"], cwd=ROOT)
    with tempfile.TemporaryDirectory(prefix="third-checker-") as d:
        path = os.path.join(d, "corpus.wiz")
        with open(path, "wb") as f:
            f.write(src)
        cmd = [wiz_bin, "run", path]
        try:
            out = subprocess.run(cmd, cwd=ROOT, timeout=timeout,
                                 stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        except FileNotFoundError:
            print(f"harness: {wiz_bin} not found (build it with `lake build wiz`, "
                  f"or use nix develop)", file=sys.stderr)
            return 2
        except subprocess.TimeoutExpired:
            print(f"harness: the kernel run timed out after {timeout}s", file=sys.stderr)
            return 2
        if out.returncode != 0:
            sys.stderr.write(out.stderr.decode("utf-8", "replace"))
            print(f"harness: the kernel run failed ({out.returncode})", file=sys.stderr)
            return 2
        text = out.stdout.decode("utf-8")
        # `wiz check` prefixes interpreter output with `file:line: info: "..."`; under
        # `wiz run` the lines are plain.  Accept both, and unquote the info form.
        lines = []
        for line in text.split("\n"):
            if ": info: " in line:
                import ast
                line = ast.literal_eval(line.split(": info: ", 1)[1])
                lines.extend(line.split("\n"))
            elif line:
                lines.append(line)
        # keep the kernel's messages for rejected declarations, drop the empty ones
        lines = [l for l in lines
                 if not l.startswith("#checking")
                 and not (l.startswith("#err") and len(l.split(" ", 2)) < 3)
                 and not (l.startswith("#err") and not l.split(" ", 2)[2].strip())]
        text = "\n".join(lines) + "\n"
        # refuse to write a dump that is not exactly one line per declaration
        rows = checker.read_dump(text)
        n = subprocess.check_output([sys.executable, DRIVER, "--names"], cwd=ROOT)
        if len(rows) != len(n.splitlines()):
            print(f"harness: the kernel produced {len(rows)} lines for "
                  f"{len(n.splitlines())} declarations", file=sys.stderr)
            return 2
        with open(DUMP, "w") as f:
            f.write("# tools/third-checker/corpus.dump -- generated by `harness.py --regen`; do not edit\n")
            f.write("# lines: OK|ERR<TAB>name<TAB>type<TAB>value; #err lines carry the kernel's message\n")
            f.write(text)
        print(f"wrote {DUMP} ({len(rows)} declarations)")
    return 0


def report(rows, verbose):
    counts = {"kernel-ok": 0, "kernel-err": 0, "kernel-crash": 0,
              "checker-ok": 0, "checker-err": 0, "mismatch": 0, "crash": 0}
    for verdict, name, ok, msg in rows:
        if verdict == "OK":
            counts["kernel-ok"] += 1
        elif verdict == "ERR":
            counts["kernel-err"] += 1
        else:
            counts["kernel-crash"] += 1
        counts["checker-ok" if ok else "checker-err"] += 1
        if verdict == "CRASH":
            counts["crash"] += 1
            print(f"CRASH\t{name}\tchecker={'accept' if ok else 'reject'}\t{msg}")
        elif (verdict == "OK") != ok:
            counts["mismatch"] += 1
            print(f"MISMATCH\t{name}\tkernel={verdict} "
                  f"checker={'OK' if ok else 'ERR'}\t{msg}")
        elif verbose:
            print(f"{'OK' if ok else 'ERR'}\t{name}\t{msg}")
    print(f"{len(rows)} declarations: kernel {counts['kernel-ok']} accepted, "
          f"{counts['kernel-err']} rejected, {counts['kernel-crash']} crashed; "
          f"checker {counts['checker-ok']} accepted, {counts['checker-err']} rejected; "
          f"{counts['mismatch']} mismatches")
    return counts["mismatch"] + counts["crash"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--regen", action="store_true",
                    help="regenerate the dump by running the selfhost kernel")
    ap.add_argument("--dump", default=DUMP)
    ap.add_argument("--wiz", default=os.environ.get("WIZ_BIN", ".lake/build/bin/wiz"))
    ap.add_argument("--timeout", type=int, default=900)
    ap.add_argument("--verbose", "-v", action="store_true")
    args = ap.parse_args()
    if args.regen:
        rc = regen(args.wiz, args.timeout)
        if rc:
            return rc
    with open(args.dump) as f:
        rows = checker.check_dump(f.read())
    return 1 if report(rows, args.verbose) else 0


if __name__ == "__main__":
    sys.exit(main())
